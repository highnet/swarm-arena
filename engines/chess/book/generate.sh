#!/usr/bin/env bash
# Regenerates the chess engine's own opening book (#108) from its own search. Offline only.
# Roots: the initial position plus every start line of the referee's balanced suite
# (shared/src/openings/chess.txt): the suite only says where games start; every move stored is
# this engine's fixed-depth search. The engine is single-threaded, so the work is sharded as
# processes here. Output is deterministic for the same parameters and engine source.
#   usage: engines/chess/book/generate.sh [depth] [reply-depth] [replies] [book-moves] [shards] [resume.txt]
# resume.txt: book lines from an interrupted run; its finished roots are skipped and its lines kept.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
engines="$here/../.."
depth="${1:-10}" reply_depth="${2:-6}" replies="${3:-3,2}" book_moves="${4:-3}" shards="${5:-4}" resume="${6:-/dev/null}"
(cd "$engines" && cargo build --release -p chess-engine)
bin="$engines/target/release/chess-engine"
work="$(mktemp -d)"
{ echo; grep -v '^#' "$engines/../shared/src/openings/chess.txt" | cut -f1; } > "$work/roots.txt"
for s in $(seq 0 $((shards - 1))); do
  "$bin" book gen "$s" "$shards" "$depth" "$reply_depth" "$replies" "$book_moves" "$resume" \
    < "$work/roots.txt" > "$work/shard$s.txt" 2> "$work/shard$s.log" &
done
wait
{
  echo "# Chess engine's own opening book (#108). Generated by book/generate.sh $depth $reply_depth $replies $book_moves"
  echo "# FEN<TAB>move<TAB>score (cp, side to move)<TAB>search depth. Duplicates across shards: first kept."
  cat "$work"/shard*.txt "$resume" | grep -v '^#' | sort -t$'\t' -k1,1 -u
} > "$here/book.txt"
"$bin" book pack < "$here/book.txt" > "$here/book.bin"
echo "book: $(grep -vc '^#' "$here/book.txt") positions, $(wc -c < "$here/book.bin") bytes"
rm -rf "$work"

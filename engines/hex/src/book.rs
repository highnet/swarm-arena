//! Self-generated opening book (#111). Every entry is a position the engine's own MCTS searched
//! offline for far longer than a game allows (`gen-book`, `src/bin/gen-book.rs`); nothing in it
//! comes from an external book or from another engine. It covers every position after one and
//! after two plies (the referee starts each pair from a random 2-ply line), up to the board's
//! 180° rotation, which maps Black's edges to Black's and White's to White's.
//!
//! `book.txt`: one position a line, `<black cells> / <white cells> <best move> <win rate>`, the
//! cells as referee moves (`f6`), the win rate for the side to move. The engine keys the table
//! by position (both bitboards, canonical under the rotation), so move order does not matter.

use std::collections::HashMap;

/// The checked-in book, generated by `cargo run --release --bin gen-book` (see the playbook).
const BOOK: &str = include_str!("book.txt");

/// The board turned by 180°: cell i goes to 120 − i.
pub fn rotate(x: u128) -> u128 {
    x.reverse_bits() >> 7
}

/// The position's canonical form: the smaller of it and its rotation. `true` when rotated.
pub fn canonical(black: u128, white: u128) -> ((u128, u128), bool) {
    let r = (rotate(black), rotate(white));
    if r < (black, white) {
        (r, true)
    } else {
        ((black, white), false)
    }
}

/// Parse a referee cell (`a1`..`k11`) to its index `row * 11 + column`.
pub fn cell(s: &str) -> Option<u8> {
    let b = s.as_bytes();
    let col = b.first()?.checked_sub(b'a')?;
    let row: u8 = s.get(1..)?.parse().ok()?;
    (col < 11 && (1..=11).contains(&row) && s.len() <= 3).then_some((row - 1) * 11 + col)
}

/// Format a cell index as a referee move.
#[allow(dead_code)] // used by gen-book and the tests
pub fn name(i: u8) -> String {
    format!("{}{}", (b'a' + i % 11) as char, i / 11 + 1)
}

/// Cells of a bitboard, as referee moves, in index order.
#[allow(dead_code)] // used by gen-book and the tests
pub fn names(x: u128) -> Vec<String> {
    (0..121u8).filter(|&i| x >> i & 1 == 1).map(name).collect()
}

/// One line of `book.txt` for a canonical position.
#[allow(dead_code)] // used by gen-book and the tests
pub fn line(black: u128, white: u128, mv: u8, winrate: f32) -> String {
    format!(
        "{} / {} {} {:.3}",
        names(black).join(" "),
        names(white).join(" "),
        name(mv),
        winrate
    )
}

/// One parsed entry: position, move, win rate.
pub fn parse(line: &str) -> Option<(u128, u128, u8, f32)> {
    let (b, rest) = line.split_once('/')?;
    let mut black = 0u128;
    for c in b.split_whitespace() {
        black |= 1u128 << cell(c)?;
    }
    let mut parts: Vec<&str> = rest.split_whitespace().collect();
    let winrate: f32 = parts.pop()?.parse().ok()?;
    let mv = cell(parts.pop()?)?;
    let mut white = 0u128;
    for c in parts {
        white |= 1u128 << cell(c)?;
    }
    Some((black, white, mv, winrate))
}

/// The book, keyed by canonical position.
pub struct Book(HashMap<(u128, u128), u8>);

impl Book {
    pub fn load() -> Self {
        Self::from_text(BOOK)
    }

    pub fn from_text(text: &str) -> Self {
        let mut map = HashMap::new();
        for l in text.lines() {
            if l.starts_with('#') || l.trim().is_empty() {
                continue;
            }
            if let Some((b, w, mv, _)) = parse(l) {
                map.insert(canonical(b, w).0, mv);
            }
        }
        Book(map)
    }

    #[allow(dead_code)] // used by gen-book and the tests
    pub fn len(&self) -> usize {
        self.0.len()
    }

    /// The book move (cell index) for this position, if it has one.
    pub fn probe(&self, black: u128, white: u128) -> Option<u8> {
        let (key, rotated) = canonical(black, white);
        let mv = *self.0.get(&key)?;
        Some(if rotated { 120 - mv } else { mv })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::board::ALL;

    #[test]
    fn rotation_is_an_involution_and_maps_cells() {
        for i in 0..121u32 {
            assert_eq!(rotate(1u128 << i), 1u128 << (120 - i));
        }
        assert_eq!(rotate(ALL), ALL);
        let x = 0x1234_5678_9abc_def0_1357_9bdf_u128 & ALL;
        assert_eq!(rotate(rotate(x)), x);
    }

    #[test]
    fn cell_names_round_trip() {
        for i in 0..121u8 {
            assert_eq!(cell(&name(i)), Some(i));
        }
        assert_eq!(cell("a1"), Some(0));
        assert_eq!(cell("k11"), Some(120));
        assert_eq!(cell("l1"), None);
        assert_eq!(cell("a12"), None);
        assert_eq!(cell("a0"), None);
    }

    #[test]
    fn line_round_trips() {
        let (b, w) = (1u128 << 60 | 1u128 << 3, 1u128 << 70);
        let (pb, pw, mv, wr) = parse(&line(b, w, 17, 0.625)).unwrap();
        assert_eq!((pb, pw, mv), (b, w, 17));
        assert!((wr - 0.625).abs() < 1e-6);
    }

    /// Every stored move is an empty cell of its position, the stones are a reachable position
    /// (Black has as many stones as White or one more) and the side to move has not lost yet.
    #[test]
    fn book_moves_are_legal_in_every_stored_position() {
        let mut n = 0;
        for l in BOOK.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
            let (b, w, mv, wr) = parse(l).unwrap_or_else(|| panic!("bad book line: {l}"));
            assert_eq!(b & w, 0, "{l}");
            let (nb, nw) = (b.count_ones(), w.count_ones());
            assert!(nb == nw || nb == nw + 1, "{l}");
            assert_eq!((b | w) >> mv & 1, 0, "book move on a stone: {l}");
            assert!((0.0..=1.0).contains(&wr), "{l}");
            assert_eq!(canonical(b, w).0, (b, w), "stored position not canonical: {l}");
            n += 1;
        }
        assert_eq!(Book::load().len(), n, "duplicate positions in the book");
    }

    /// Coverage: every one- and two-ply position is in the book, and a rotated probe returns
    /// the rotated move.
    #[test]
    fn book_covers_every_one_and_two_ply_position() {
        let book = Book::load();
        for a in 0..121u32 {
            assert!(book.probe(1u128 << a, 0).is_some(), "ply 1: {}", name(a as u8));
            for c in (0..121u32).filter(|&c| c != a) {
                let (b, w) = (1u128 << a, 1u128 << c);
                let mv = book.probe(b, w).unwrap_or_else(|| panic!("ply 2: {} {}", name(a as u8), name(c as u8)));
                assert_eq!((b | w) >> mv & 1, 0);
                assert_eq!(book.probe(rotate(b), rotate(w)), Some(120 - mv));
            }
        }
    }
}
